#!/usr/bin/env python3
"""Generate python/pypdf/_api_annotations.py from the REFERENCE pypdf.

The Rust port's shims lose the upstream type annotations (Rust functions cannot
carry `__annotations__`, and shims use `Any`).  This script captures the
reference annotations as rendered strings; the generated module applies them at
import time by evaluating the strings back into real objects, so that
`inspect.signature` output matches the reference exactly.
"""
from __future__ import annotations

import importlib
import inspect
import json
import pkgutil
import pprint
import sys
from pathlib import Path

import pypdf

SKIP_MODULES = {"pypdf._pypdf"}


def rendered(fn) -> dict | None:
    try:
        sig = inspect.signature(fn)
    except (ValueError, TypeError):
        return None
    from inspect import formatannotation

    params = {}
    for name, param in sig.parameters.items():
        if param.annotation is inspect.Parameter.empty:
            continue
        params[name] = formatannotation(param.annotation)
    ret = None
    if sig.return_annotation is not inspect.Signature.empty:
        ret = formatannotation(sig.return_annotation)
    if not params and ret is None:
        return None
    return {"params": params, "return": ret}


def collect() -> dict:
    table: dict[str, dict] = {}
    for info in pkgutil.walk_packages(pypdf.__path__, prefix="pypdf."):
        name = info.name
        if name in SKIP_MODULES:
            continue
        try:
            mod = importlib.import_module(name)
        except Exception:
            continue
        for attr, obj in vars(mod).items():
            if attr.startswith("__"):
                continue
            key = f"{name}.{attr}"
            if inspect.isfunction(obj):
                entry = rendered(obj)
                if entry:
                    table[key] = entry
            elif inspect.isclass(obj) and obj.__module__.startswith("pypdf"):
                for mname, mobj in vars(obj).items():
                    if mname.startswith("__") and mname != "__init__":
                        continue
                    raw = mobj.__func__ if isinstance(mobj, (staticmethod, classmethod)) else mobj
                    if inspect.isfunction(raw):
                        entry = rendered(raw)
                        if entry:
                            table[f"{key}.{mname}"] = entry
    return table


def main() -> int:
    table = collect()
    out = Path(sys.argv[1])
    lines = [
        '"""Reference API annotations, generated by validation/gen_api_annotations.py.',
        "",
        "Applied at package import so `inspect.signature` matches upstream pypdf.",
        "Do not edit by hand.",
        '"""',
        "from __future__ import annotations",
        "",
        "TABLE = ",
    ]
    lines[-1] += pprint.pformat(table, width=110, sort_dicts=True)
    lines += [
        "",
        "FAILED: list[str] = []",
        "",
        "",
        "def _namespace():",
        "    import collections",
        "    import collections.abc",
        "    import datetime",
        "    import decimal",
        "    import pathlib",
        "    import typing",
        "",
        "    import pypdf",
        "",
        "    ns = {name: getattr(typing, name) for name in dir(typing) if not name.startswith('_')}",
        "    ns.update({name: getattr(collections.abc, name) for name in dir(collections.abc) if not name.startswith('_')})",
        "    ns.update({'pypdf': pypdf, 'collections': collections, 'typing': typing,",
        "               'datetime': datetime, 'decimal': decimal, 'pathlib': pathlib,",
        "               'Path': pathlib.Path, 'IO': typing.IO, 'Any': typing.Any,",
        "               'os': __import__('os'), 'io': __import__('io'), 're': __import__('re'),",
        "               'types': __import__('types')})",
        "    return ns",
        "",
        "",
        "_NS = None",
        "",
        "",
        "",
        "class _Rendered:",
        "    # Fallback annotation whose repr matches the reference text exactly.",
        "",
        "    __module__ = 'typing'",
        "    __slots__ = ('_text',)",
        "",
        "    def __init__(self, text):",
        "        self._text = text",
        "",
        "    def __repr__(self):",
        "        return self._text",
        "",
        "",
        "def _evaluate(text):",
        "    # Never let annotation materialisation import a pypdf submodule: doing so",
        "    # would change import timing (several modules are imported lazily, e.g.",
        "    # generic._image_xobject) and alter observable behaviour.  For strings",
        "    # referencing the package, keep the reference text verbatim.",
        "    if 'pypdf.' in text:",
        "        return _Rendered(text)",
        "    global _NS",
        "    if _NS is None:",
        "        _NS = _namespace()",
        "    try:",
        "        return eval(text, {'__builtins__': __builtins__}, _NS)  # noqa: S307 - trusted, generated table",
        "    except Exception:",
        "        FAILED.append(text)",
        "        return _Rendered(text)",
        "",
        "",
        "import inspect",
        "",
        "",
        "def apply_module(namespace):",
        '    """Apply the annotations belonging to one module (called by each shim)."""',
        "    mod_name = namespace.get('__name__', '')",
        "    prefix = mod_name + '.'",
        "    for key, entry in TABLE.items():",
        "        if not key.startswith(prefix):",
        "            continue",
        "        parts = key[len(prefix):].split('.')",
        "        obj = namespace.get(parts[0])",
        "        for part in parts[1:]:",
        "            if obj is None:",
        "                break",
        "            obj = getattr(obj, part, None)",
        "        if obj is None or not callable(obj):",
        "            continue",
        "        ann = {name: _evaluate(text) for name, text in entry['params'].items()}",
        "        if entry.get('return') is not None:",
        "            ann['return'] = _evaluate(entry['return'])",
        "        targets = [obj]",
        "        try:",
        "            inner = inspect.unwrap(obj)",
        "            if inner is not obj:",
        "                targets.append(inner)",
        "        except Exception:",
        "            pass",
        "        for target in targets:",
        "            try:",
        "                target.__annotations__ = ann",
        "            except (AttributeError, TypeError):",
        "                continue",
        "",
    ]
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"annotations: {len(table)} entries -> {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

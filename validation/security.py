def safe_repr(value, limit=300):
    try:
        text = repr(value)
    except Exception:
        return "<unreprable>"
    text = re.sub(r"0x[0-9a-fA-F]+", "0xADDR", text)
    return text[:limit]


def summarize(value, depth=0, stack=None):
    """Bounded, cycle-safe, JSON-serialisable summary of an arbitrary value."""
    if stack is None:
        stack = set()
    if depth > 6:
        return {"$": "depth-limit", "depth": depth}
    if value is None or isinstance(value, (bool, int, float)):
        if isinstance(value, float) and (value != value or value in (float("inf"), float("-inf"))):
            return {"$": "non-finite-float", "repr": repr(value)}
        return value
    if isinstance(value, str):
        if len(value) <= 120:
            return value
        return {"str_len": len(value), "head": value[:80]}
    if isinstance(value, (bytes, bytearray)):
        raw = bytes(value)
        return {"bytes": len(raw), "sha256": hashlib.sha256(raw).hexdigest()}
    marker = id(value)
    if marker in stack:
        return {"$": "cycle"}
    stack.add(marker)
    try:
        if isinstance(value, dict):
            items = []
            for index, (key, item) in enumerate(value.items()):
                if index >= 40:
                    items.append({"$": "truncated", "total": len(value)})
                    break
                items.append(
                    [summarize(key, depth + 1, stack), summarize(item, depth + 1, stack)]
                )
            return {"dict": items, "size": len(value), "type": type(value).__name__}
        if isinstance(value, (list, tuple)):
            items = [summarize(item, depth + 1, stack) for item in list(value)[:40]]
            return {"list": items, "size": len(value), "type": type(value).__name__}
        return {"type": type(value).__name__, "repr": safe_repr(value)}
    finally:
        stack.discard(marker)


class Session:
    def __init__(self, path, write_out, resolve_path):
        self.path = path
        self.write_out = write_out
        self.resolve_path = list(resolve_path or [])
        self._reader = None
        self._reader_error = None

    # -- helpers ---------------------------------------------------------
    def reader(self):
        if self._reader is None and self._reader_error is None:
            try:
                from pypdf import PdfReader

                self._reader = PdfReader(self.path, strict=False)
            except BaseException as exc:  # noqa: BLE001 - failures are data
                self._reader_error = exc
                raise
        if self._reader_error is not None:
            raise self._reader_error
        return self._reader

    @staticmethod
    def _resolve(value):
        if hasattr(value, "get_object"):
            return value.get_object()
        return value

    def _walk(self):
        reader = self.reader()
        node = self._resolve(reader.trailer["/Root"])
        for key in self.resolve_path:
            node = self._resolve(node)
            node = node[key]
        return self._resolve(node)

    # -- steps -----------------------------------------------------------
    def step_parse(self):
        reader = self.reader()
        trailer = reader.trailer
        root = reader.root_object
        # Bookkeeping for plan §8.3 (actual object count); best effort only so
        # that an internal-detail difference can never mask the decision.
        accounting = {
            "num_xref_objects": None,
            "num_xref_generations": None,
            "num_free_entries": None,
            "num_object_streams": None,
        }
        try:
            xref = getattr(reader, "xref", None) or {}
            num_objects = 0
            generations = 0
            for entries in xref.values():
                generations += 1
                num_objects += len(entries)
            num_free = 0
            for entries in (getattr(reader, "xref_free_entry", None) or {}).values():
                num_free += sum(1 for value in entries.values() if value)
            accounting = {
                "num_xref_objects": num_objects,
                "num_xref_generations": generations,
                "num_free_entries": num_free,
                "num_object_streams": len(getattr(reader, "xref_objStm", None) or {}),
            }
        except Exception:  # noqa: BLE001 - evidence only
            pass
        return {
            "is_encrypted": bool(reader.is_encrypted),
            "root_type": type(root).__name__,
            "trailer_keys": sorted(str(key) for key in trailer.keys())[:20],
            **accounting,
        }

    def step_pages(self):
        reader = self.reader()
        pages = reader.pages
        first = None
        if len(pages):
            page = pages[0]
            first = {
                "page_type": type(page).__name__,
                "rotation": int(page.rotation or 0),
                "mediabox": [float(x) for x in list(page.mediabox)],
            }
        return {"num_pages": len(pages), "first_page": first}

    def step_text(self):
        reader = self.reader()
        pages = reader.pages
        if not len(pages):
            return {"num_pages": 0, "text_len": 0, "sha256": None, "head": ""}
        text = pages[0].extract_text() or ""
        encoded = text.encode("utf-8", "surrogatepass")
        return {
            "num_pages": len(pages),
            "text_len": len(text),
            "sha256": hashlib.sha256(encoded).hexdigest(),
            "head": text[:120],
        }

    def step_outline(self):
        reader = self.reader()
        value = reader.outline
        entries = 0
        max_depth = 0
        stack = [(value, 0)]
        nodes = 0
        while stack and entries < 50000 and nodes < 200000:
            node, depth = stack.pop()
            nodes += 1
            if isinstance(node, (list, tuple)):
                max_depth = max(max_depth, depth + 1)
                for child in node:
                    stack.append((child, depth + 1))
            else:
                entries += 1
        return {"entries": entries, "max_container_depth": max_depth}

    def step_labels(self):
        reader = self.reader()
        labels = list(reader.page_labels)
        return {"num_labels": len(labels), "head": [str(x) for x in labels[:10]]}

    def step_attachments(self):
        reader = self.reader()
        names = list(reader.attachments.keys())
        details = []
        for name in names[:5]:
            parts = reader.attachments[name]
            details.append(
                {"name": summarize(name), "parts": len(parts), "sizes": [len(p) for p in parts]}
            )
        return {
            "num_attachments": len(names),
            "names": [summarize(name) for name in names[:10]],
            "details": details,
        }

    def step_fields(self):
        reader = self.reader()
        fields = reader.get_fields() or {}
        return {"num_fields": len(fields), "names": [str(key) for key in list(fields)[:10]]}

    def step_annotations(self):
        reader = self.reader()
        pages = reader.pages
        if not len(pages):
            return {"num_annotations": 0, "types": []}
        page = pages[0]
        if "/Annots" not in page:
            return {"num_annotations": 0, "types": []}
        annotations = list(page.annotations)
        return {
            "num_annotations": len(annotations),
            "types": [type(item).__name__ for item in annotations[:10]],
        }

    def step_operations(self):
        reader = self.reader()
        pages = reader.pages
        if not len(pages):
            return {"num_operations": 0, "head": []}
        contents = pages[0].get_contents()
        if contents is None:
            return {"num_operations": 0, "head": []}
        operations = list(contents.operations)
        return {
            "num_operations": len(operations),
            "head": [str(item[0]) for item in operations[:20]],
        }

    def step_resolve(self):
        node = self._walk()
        if hasattr(node, "get_data"):
            data = node.get_data()
            return {
                "stream_bytes": len(data),
                "sha256": hashlib.sha256(data).hexdigest(),
                "path": list(self.resolve_path),
            }
        return {"value": summarize(node), "path": list(self.resolve_path)}

    def step_depth(self):
        node = self._walk()
        max_depth = 0
        nodes = 0
        seen = set()
        stack = [(node, 1)]
        budget = 200000
        while stack and nodes < budget:
            current, depth = stack.pop()
            nodes += 1
            max_depth = max(max_depth, depth)
            marker = id(current)
            if marker in seen:
                continue
            seen.add(marker)
            if isinstance(current, dict):
                children = list(current.values())
            elif isinstance(current, (list, tuple)):
                children = list(current)
            else:
                continue
            if depth >= 30000:
                continue
            for child in children:
                stack.append((child, depth + 1))
        return {
            "max_depth": max_depth,
            "nodes": nodes,
            "truncated": nodes >= budget,
            "container_type": type(node).__name__,
        }

    def step_cycle(self):
        node = self._walk()
        seen = {}
        steps = 0
        while steps < 100:
            marker = id(node)
            if marker in seen:
                return {
                    "cycle_detected": True,
                    "repeat_after": steps - seen[marker],
                    "steps": steps,
                    "type": type(node).__name__,
                }
            seen[marker] = steps
            if not isinstance(node, dict) or "/Next" not in node:
                break
            node = self._resolve(node["/Next"])
            steps += 1
        return {
            "cycle_detected": False,
            "repeat_after": None,
            "steps": steps,
            "type": type(node).__name__,
        }

    def step_write(self):
        from pypdf import PdfWriter

        reader = self.reader()
        writer = PdfWriter()
        writer.append(reader)
        with open(self.write_out, "wb") as handle:
            writer.write(handle)
        return {"out_path": self.write_out, "bytes": os.path.getsize(self.write_out)}



_MESSAGE_ADDRESS_PATTERNS = (
    # IndirectObject(5, 0, 4457620752) -- the third argument is id(pdf)
    (re.compile(r"(IndirectObject\(\s*\d+\s*,\s*\d+\s*,\s*)\d+(\s*\))"), r"\1ADDR\2"),
    (re.compile(r"0x[0-9a-fA-F]{6,}"), "0xADDR"),
)


def normalize_message(text: Any) -> Any:
    """Strip object addresses from a message before text comparison.

    pypdf embeds ``id(pdf)`` in some reprs, so the raw text legitimately
    differs between two processes.  The raw messages are kept in the evidence;
    only the comparison and the report use the normalised form.
    """
    if not isinstance(text, str):
        return text
    normalised = text
    for pattern, replacement in _MESSAGE_ADDRESS_PATTERNS:
        normalised = pattern.sub(replacement, normalised)
    return normalised


# Values that are directly comparable between the two implementations.  Only

def apply_limits(limit_as_mb, probe_timeout):
    import resource

    info = {
        "requested_as_mb": limit_as_mb,
        "as_applied": False,
        "as_error": None,
        "cpu_limit_s": None,
        "cpu_applied": False,
        "cpu_error": None,
        "platform": sys.platform,
    }
    if limit_as_mb:
        try:
            nbytes = int(limit_as_mb) * 1024 * 1024
            resource.setrlimit(resource.RLIMIT_AS, (nbytes, nbytes))
            info["as_applied"] = True
        except Exception as exc:  # noqa: BLE001 - macOS rejects RLIMIT_AS
            info["as_error"] = f"{type(exc).__name__}: {exc}"
    # CPU backstop: parent wall-clock timeout always fires first.
    cpu_limit = int(max(5.0, probe_timeout + 15.0))
    try:
        resource.setrlimit(resource.RLIMIT_CPU, (cpu_limit, cpu_limit + 5))
        info["cpu_limit_s"] = cpu_limit
        info["cpu_applied"] = True
    except Exception as exc:  # noqa: BLE001
        info["cpu_error"] = f"{type(exc).__name__}: {exc}"
    return info


def rss_bytes():
    import resource

    usage = resource.getrusage(resource.RUSAGE_SELF)
    value = int(usage.ru_maxrss)
    # Linux reports kibibytes, macOS reports bytes.
    if sys.platform != "darwin":
        value *= 1024
    return value


def cpu_seconds():
    import resource

    usage = resource.getrusage(resource.RUSAGE_SELF)
    return round(usage.ru_utime + usage.ru_stime, 4)


def write_record(path, record):
    target = path + ".tmp"
    with open(target, "w", encoding="utf-8") as handle:
        json.dump(record, handle, indent=1, sort_keys=True, default=str)
        handle.write("\n")
    os.replace(target, path)



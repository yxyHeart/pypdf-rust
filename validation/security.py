def git_commit() -> str:
    try:
        completed = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"],
            cwd=str(ROOT),
            capture_output=True,
            text=True,
            timeout=10,
        )
        if completed.returncode == 0:
            return completed.stdout.strip()
    except Exception:  # noqa: BLE001
        pass
    return "unknown"


def load_json(path: Path) -> dict[str, Any] | None:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except Exception:  # noqa: BLE001
        return None


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--heavy", action="store_true", help="include decompression bombs (slow)")
    parser.add_argument("--work-dir", type=Path, default=None, help="corpus/probe work directory")
    parser.add_argument("--keep-corpus", action="store_true", help="copy the corpus into validation/results/security-corpus")
    parser.add_argument("--cases", default=None, help="only run case ids matching this regex")
    parser.add_argument("--backends", default="oracle,port", help="comma separated subset of oracle,port")
    parser.add_argument(
        "--limit-as-mb",
        type=int,
        default=1024,
        help="RLIMIT_AS for the probe subprocess (0 disables; ignored on platforms that reject it)",
    )
    parser.add_argument("--generate-only", action="store_true", help="only build the corpus + manifest")
    parser.add_argument("--render-report", action="store_true", help="only re-render security-report.md")
    parser.add_argument("--list-cases", action="store_true", help="print the case inventory and exit")
    args = parser.parse_args(argv)

    try:
        RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    except OSError as exc:
        print(f"[security] cannot create {RESULTS_DIR}: {exc}", file=sys.stderr)
        return 2

    if args.render_report:
        comparison = load_json(COMPARISON_OUT)
        oracle = load_json(RESULTS_DIR / "security-oracle.json")
        port = load_json(RESULTS_DIR / "security-port.json")
        manifest = load_json(MANIFEST_OUT)
        fuzz = load_json(RESULTS_DIR / "fuzz-comparison.json")
        REPORT_OUT.write_text(
            render_report(comparison=comparison, oracle=oracle, port=port, manifest=manifest, fuzz=fuzz),
            encoding="utf-8",
        )
        print(f"[security] report written to {REPORT_OUT}")
        return 0

    all_cases = build_case_list()
    if args.list_cases:
        for case in all_cases:
            flag = "heavy" if case.heavy else "default"
            print(f"{case.id:36s} {case.category:12s} {flag:8s} {case.intent}")
        return 0

    selected = all_cases
    if args.cases:
        pattern = re.compile(args.cases)
        selected = [case for case in all_cases if pattern.search(case.id)]
        if not selected:
            print(f"[security] no case matches {args.cases!r}", file=sys.stderr)
            return 2

    backends = [item.strip() for item in args.backends.split(",") if item.strip()]
    unknown = [item for item in backends if item not in PYTHON_EXE]
    if unknown:
        print(f"[security] unknown backend(s): {unknown}", file=sys.stderr)
        return 2

    work_dir = args.work_dir
    temporary = work_dir is None
    if temporary:
        work_dir = Path(tempfile.mkdtemp(prefix="pypdf-sec-corpus-"))
    work_dir.mkdir(parents=True, exist_ok=True)
    corpus_dir = work_dir / "corpus"
    out_root = work_dir / "out"

    probe_path = work_dir / "_probe_security.py"
    probe_path.write_text(PROBE_SOURCE, encoding="utf-8")

    print(f"[security] work dir: {work_dir}")
    manifest_entries = generate_corpus(selected, corpus_dir, args.heavy)
    generated = [entry for entry in manifest_entries if entry.get("generated")]
    skipped = [entry for entry in manifest_entries if not entry.get("generated")]
    total_bytes = sum(entry.get("size_bytes", 0) for entry in generated)
    generated_ids = {entry["id"] for entry in manifest_entries if entry.get("generated")}
    generated_case_objs = [case for case in selected if case.id in generated_ids]
    coverage = build_coverage(generated_case_objs)
    manifest = {
        "generated_at": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "generator": "validation/security.py",
        "git_commit": git_commit(),
        "heavy": args.heavy,
        "limit_as_mb": args.limit_as_mb,
        "totals": {
            "cases": len(manifest_entries),
            "generated_cases": len(generated),
            "skipped_heavy": len(skipped),
            "total_bytes": total_bytes,
        },
        "coverage": coverage,
        "cases": manifest_entries,
    }
    MANIFEST_OUT.write_text(json.dumps(manifest, indent=1, sort_keys=True) + "\n", encoding="utf-8")
    print(
        f"[security] corpus: {len(generated)} case(s), {total_bytes} bytes, "
        f"{len(skipped)} skipped (heavy) -> {corpus_dir}"
    )

    if args.generate_only:
        if args.keep_corpus:
            if KEPT_CORPUS_DIR.exists():
                shutil.rmtree(KEPT_CORPUS_DIR)
            shutil.copytree(corpus_dir, KEPT_CORPUS_DIR)
            print(f"[security] corpus copied to {KEPT_CORPUS_DIR}")
        print(f"[security] manifest written to {MANIFEST_OUT}")
        if temporary:
            shutil.rmtree(work_dir, ignore_errors=True)
        return 0

    run_cases = [case for case in selected if any(e["id"] == case.id and e.get("generated") for e in manifest_entries)]
    backends_payload: dict[str, dict[str, Any]] = {}
    for backend in backends:
        print(f"[security] running {len(run_cases)} case(s) in the {backend} venv ...")
        started = time.monotonic()
        fingerprint_before = package_fingerprint(backend)
        payload = run_backend(
            backend=backend,
            cases=run_cases,
            corpus_dir=corpus_dir,
            probe_path=probe_path,
            out_root=out_root,
            limit_as_mb=args.limit_as_mb,
            manifest_entries=manifest_entries,
        )
        elapsed = time.monotonic() - started
        fingerprint_after = package_fingerprint(backend)
        payload["environment"] = {
            "fingerprint_before": fingerprint_before,
            "fingerprint_after": fingerprint_after,
            "stable": fingerprint_before == fingerprint_after,
        }
        if fingerprint_before != fingerprint_after:
            print(
                f"[security] WARNING: the {backend} pypdf package changed during the run "
                "(concurrent rebuild?) - this run is torn and must be repeated",
                file=sys.stderr,
            )
        backends_payload[backend] = payload
        output = RESULTS_DIR / f"security-{backend}.json"
        output.write_text(json.dumps(payload, indent=1, sort_keys=True) + "\n", encoding="utf-8")
        summary = payload.get("summary") or {}
        print(
            "[security] {}: {} case(s), ok={}, raised={}, limit_reached={}, "
            "timeouts={}, crashes={}, panics={}, max_rss={} B, wall={:.1f}s -> {}".format(
                backend,
                summary.get("cases", 0),
                summary.get("ok", 0),
                summary.get("errors", 0),
                summary.get("limit_reached", 0),
                summary.get("timeouts", 0),
                summary.get("crashes", 0),
                summary.get("panics", 0),
                summary.get("max_rss_bytes", 0),
                elapsed,
                output,
            )
        )

    comparison_meta = {
        "generated_at": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "heavy": args.heavy,
        "git_commit": manifest["git_commit"],
        "corpus": {
            "work_dir": str(work_dir),
            "generated_cases": len(generated),
            "skipped_heavy": len(skipped),
            "total_bytes": total_bytes,
            "heavy": args.heavy,
            "manifest": str(MANIFEST_OUT),
        },
    }
    comparison = None
    if "oracle" in backends_payload and "port" in backends_payload:
        comparison = compare_backends(backends_payload["oracle"], backends_payload["port"], comparison_meta)
        COMPARISON_OUT.write_text(json.dumps(comparison, indent=1, sort_keys=True) + "\n", encoding="utf-8")
        summary = comparison["summary"]
        print(
            "[security] comparison: {} ({} blocking, {} message-only case(s), "
            "{} timeout(s), {} crash(es)) -> {}".format(
                comparison["overall"],
                summary["blocking"],
                summary["message_diff_cases"],
                summary["timeouts"],
                summary["crashes"],
                COMPARISON_OUT,
            )
        )
    else:
        comparison = load_json(COMPARISON_OUT)

    REPORT_OUT.write_text(
        render_report(
            comparison=comparison,
            oracle=backends_payload.get("oracle") or load_json(RESULTS_DIR / "security-oracle.json"),
            port=backends_payload.get("port") or load_json(RESULTS_DIR / "security-port.json"),
            manifest=manifest,
            fuzz=load_json(RESULTS_DIR / "fuzz-comparison.json"),
        ),
        encoding="utf-8",
    )
    print(f"[security] report written to {REPORT_OUT}")

    if args.keep_corpus:
        if KEPT_CORPUS_DIR.exists():
            shutil.rmtree(KEPT_CORPUS_DIR)
        shutil.copytree(corpus_dir, KEPT_CORPUS_DIR)
        print(f"[security] corpus copied to {KEPT_CORPUS_DIR}")

    exit_code = 0
    for backend, payload in backends_payload.items():
        summary = payload.get("summary") or {}
        if summary.get("timeouts") or summary.get("crashes") or summary.get("panics"):
            exit_code = 1
        if summary.get("unavailable") or summary.get("environment_errors"):
            exit_code = 1
        if not (payload.get("environment") or {}).get("stable", True):
            exit_code = 1
    if comparison and comparison["summary"]["blocking"]:
        exit_code = 1

    if temporary:
        shutil.rmtree(work_dir, ignore_errors=True)

    return exit_code


if __name__ == "__main__":
    raise SystemExit(main())

# ---------------------------------------------------------------------------
# Tiny PDF writer helpers.  Everything is deterministic; offsets are written
# with fixed width so that byte-level mutations stay length preserving.
# ---------------------------------------------------------------------------


def obj_bytes(num: int, body: bytes) -> bytes:
    return b"%d 0 obj\n" % num + body + b"\nendobj\n"


def stream_bytes(
    data: bytes,
    *,
    length: int | None = None,
    extra: bytes = b"",
    declare_length: bytes | None = None,
) -> bytes:
    """Build a stream object body with a correct /Length by default."""
    if declare_length is not None:
        length_part = declare_length
    else:
        length_part = b"%d" % (len(data) if length is None else length)
    return b"<< /Length " + length_part + extra + b" >>\nstream\n" + data + b"\nendstream"


def assemble(
    objects: dict[int, bytes],
    *,
    root: int | None = 1,
    header: bytes = b"%PDF-1.7",
    preamble: bytes = b"\n%\xe2\xe3\xcf\xd3\n",
    trailer_extra: bytes = b"",
    eof: bytes = b"%%EOF\n",
    order: list[int] | None = None,
    xref_shift: int = 0,
    extra_xref: list[tuple[int, dict[int, int]]] | None = None,
    size_text: bytes | None = None,
) -> bytes:
    out = bytearray()
    out += header + preamble
    offsets: dict[int, int] = {}
    for num in order if order is not None else sorted(objects):
        offsets[num] = len(out)
        out += obj_bytes(num, objects[num])
    xref_offset = len(out)
    max_num = max(objects) if objects else 1
    # ``size_text`` allows emitting a deliberately malformed subsection size
    # without shifting the fixed-width entries that follow it.
    out += b"xref\n0 " + (size_text if size_text is not None else b"%d" % (max_num + 1)) + b"\n"
    out += b"0000000000 65535 f \n"
    for num in range(1, max_num + 1):
        if num in offsets:
            out += b"%010d 00000 n \n" % ((offsets[num] + xref_shift) % 10**10)
        else:
            out += b"0000000000 65535 f \n"
    for start_num, mapping in extra_xref or []:
        out += b"%d %d\n" % (start_num, len(mapping))
        for num in sorted(mapping):
            out += b"%010d 00000 n \n" % ((offsets[mapping[num]] + xref_shift) % 10**10)
    out += b"trailer\n<< /Size %d " % (max_num + 1)
    if root is not None:
        out += b"/Root %d 0 R " % root
    out += trailer_extra
    out += b">>\nstartxref\n%d\n" % xref_offset
    out += eof
    return bytes(out)


def _xref_entry_spans(data: bytes, count: int) -> tuple[int, int]:
    """Return (entries_start, trailer_pos) for a one-subsection classic xref."""
    trailer_pos = data.rfind(b"trailer")
    if trailer_pos < 0:
        raise ValueError("no trailer in assembled PDF")
    return trailer_pos - 20 * count, trailer_pos


def _rewrite_xref_entry(data: bytes, obj_num: int, count: int, new_offset: int) -> bytes:
    entries_start, _ = _xref_entry_spans(data, count)
    pos = entries_start + 20 * obj_num
    if data[pos + 17 : pos + 18] != b"n":
        raise ValueError(f"object {obj_num} is not an in-use xref entry")
    return data[:pos] + b"%010d 00000 n \n" % new_offset + data[pos + 20 :]


def _shift_xref_offsets(data: bytes, count: int, delta: int) -> bytes:
    entries_start, _ = _xref_entry_spans(data, count)
    out = bytearray(data)
    for num in range(1, count):
        pos = entries_start + 20 * num
        if out[pos + 17 : pos + 18] != b"n":
            continue
        value = int(bytes(out[pos : pos + 10])) + delta
        out[pos : pos + 10] = b"%010d" % (value % 10**10)
    return bytes(out)


def nested_array(depth: int) -> bytes:
    return b"[" * depth + b"1" + b"]" * depth


def nested_dict(depth: int) -> bytes:
    return b"<< /a " * depth + b"1" + b" >>" * depth


def flate_bomb(total: int) -> bytes:
    """zlib stream of `total` zero bytes, built incrementally (low memory)."""
    compressor = zlib.compressobj(level=9)
    chunk = b"\x00" * (1 << 20)
    out = bytearray()
    written = 0
    while written < total:
        take = min(len(chunk), total - written)
        out += compressor.compress(chunk[:take])
        written += take
    out += compressor.flush()
    return bytes(out)



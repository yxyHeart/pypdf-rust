def cmap_stream(entries: int, *, code_hex_len: int = 4) -> bytes:
    lines = [
        b"/CIDInit /ProcSet findresource begin",
        b"12 dict begin",
        b"begincmap",
        b"/CIDSystemInfo << /Registry (Adobe) /Ordering (UCS) /Supplement 0 >> def",
        b"/CMapName /Adobe-Identity-UCS def",
        b"/CMapType 2 def",
        b"1 begincodespacerange",
        b"<0000> <FFFF>",
        b"endcodespacerange",
    ]
    code = 0
    remaining = entries
    while remaining:
        count = min(100, remaining)
        lines.append(b"%d beginbfchar" % count)
        for _ in range(count):
            target = 0x41 + (code % 26)
            source = b"%0*X" % (code_hex_len, code & ((1 << (4 * code_hex_len)) - 1))
            lines.append(b"<" + source + b"> <" + b"%04X" % target + b">")
            code += 1
        lines.append(b"endbfchar")
        remaining -= count
    lines += [
        b"endcmap",
        b"CMapName currentdict /CMap defineresource pop",
        b"end",
        b"end",
    ]
    return b"\n".join(lines)



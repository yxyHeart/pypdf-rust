def generate_corpus(cases: list[Case], corpus_dir: Path, heavy: bool) -> list[dict[str, Any]]:
    corpus_dir.mkdir(parents=True, exist_ok=True)
    manifest: list[dict[str, Any]] = []
    for case in cases:
        entry: dict[str, Any] = {
            "id": case.id,
            "category": case.category,
            "intent": case.intent,
            "expectation": case.expectation,
            "heavy": case.heavy,
            "steps": list(case.steps),
            "resolve_path": list(case.resolve_path),
            "timeout_s": case.timeout_s,
            "write": case.write,
            "note": case.note,
        }
        if not heavy and case.heavy:
            entry.update({"generated": False, "skip_reason": "requires --heavy"})
            manifest.append(entry)
            continue
        payload = case.build()
        target = corpus_dir / f"{case.id}.pdf"
        target.write_bytes(payload)
        entry.update(
            {
                "generated": True,
                "file": target.name,
                "size_bytes": len(payload),
                "sha256": hashlib.sha256(payload).hexdigest(),
            }
        )
        manifest.append(entry)
    return manifest



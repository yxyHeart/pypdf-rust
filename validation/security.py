def _fmt_bytes(value: Any) -> str:
    try:
        number = int(value or 0)
    except (TypeError, ValueError):
        return "n/a"
    if number <= 0:
        return "0"
    units = ["B", "KiB", "MiB", "GiB"]
    size = float(number)
    index = 0
    while size >= 1024 and index < len(units) - 1:
        size /= 1024.0
        index += 1
    return f"{size:.1f} {units[index]}"


def _escape(value: Any) -> str:
    text = "" if value is None else str(value)
    return text.replace("|", "\\|").replace("\n", " ")


def _case_steps_text(item: dict[str, Any], side: str) -> str:
    data = item.get(side) or {}
    if not isinstance(data, dict):
        return "n/a"
    if data.get("probe_status") == "timeout":
        return "TIMEOUT"
    if data.get("probe_status") == "crash":
        return "CRASH"
    classes = data.get("exception_classes") or {}
    if not classes:
        return "ok" if data.get("ok") else "error"
    return ", ".join(f"{name}:{cls}" for name, cls in classes.items())



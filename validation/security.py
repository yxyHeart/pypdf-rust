def build_coverage(cases: list[Case]) -> dict[str, list[str]]:
    def ids(predicate: Callable[[Case], bool]) -> list[str]:
        return [case.id for case in cases if predicate(case)]

    return {
        "Deeply nested arrays/dictionaries": ids(lambda c: c.category == "nesting"),
        "Indirect reference cycles": ids(lambda c: c.category == "cycles"),
        "Page-tree cycles": ids(lambda c: c.id.startswith("page_tree")),
        "Outline / form / annotation tree cycles": ids(
            lambda c: c.id.startswith("outline") or c.id.startswith("form") or c.id.startswith("annotation")
        ),
        "Malformed xref and wrong object offsets": ids(lambda c: c.category == "xref"),
        "Huge /Length, truncated streams": ids(
            lambda c: c.id.startswith("stream_")
        ),
        "Missing PDF header / EOF": ids(lambda c: c.id.startswith("structure_")),
        "Excessive stream filter chains": ids(lambda c: c.id.startswith("filter_")),
        "Decompression bombs": ids(lambda c: c.id.startswith("bomb_")),
        "Oversized CMap / page labels / attachment names": ids(lambda c: c.category == "oversized"),
        "Duplicate / conflicting object numbers": ids(
            lambda c: "duplicate" in c.id or "conflicting" in c.id
        ),
        "Inline image boundary errors": ids(lambda c: c.id.startswith("inline_image")),
    }



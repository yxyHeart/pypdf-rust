PANIC_PATTERNS = re.compile(
    r"panicked at|PanicException|RUST_BACKTRACE|fatal runtime error|stack overflow",
    re.IGNORECASE,
)


def looks_like_panic(stderr: str) -> bool:
    return bool(PANIC_PATTERNS.search(stderr or ""))


def package_fingerprint(backend: str) -> dict[str, Any] | None:
    """Hash every module of the pypdf package used by a backend.

    The dev venv is shared with other agents that rebuild the PyO3 extension;
    a fingerprint taken before and after a run detects a torn run (some cases
    executed against one build, later cases against another).
    """
    if backend == "port":
        package = ROOT / "python" / "pypdf"
    else:
        matches = sorted(PYTHON_EXE[backend].parents[1].glob("lib/python*/site-packages/pypdf"))
        package = matches[0] if matches else None
    if package is None or not package.exists():
        return None
    digest = hashlib.sha256()
    files = 0
    for path in sorted(package.rglob("*")):
        if not path.is_file() or path.suffix not in {".py", ".so", ".pyd", ".pyi"}:
            continue
        data = path.read_bytes()
        digest.update(path.relative_to(package).as_posix().encode())
        digest.update(b"\0")
        digest.update(hashlib.sha256(data).digest())
        files += 1
    return {"package": str(package), "files": files, "sha256": digest.hexdigest()}


def looks_like_environment_error(record: dict[str, Any] | None) -> bool:
    """Detect a broken/torn port install (import of ``pypdf._pypdf`` fails)."""
    if not record or not (record.get("import") or {}).get("ok"):
        return False
    steps = record.get("steps") or {}
    failures = [
        step for step in steps.values() if step.get("status") not in ("ok", None)
    ]
    if not failures or len(failures) != len(steps):
        return False
    for step in failures:
        error = step.get("error") or {}
        message = str(error.get("msg") or "")
        if error.get("type") not in ("ImportError", "ModuleNotFoundError"):
            return False
        if "_pypdf" not in message and "cannot import name" not in message:
            return False
    return True


def probe_env() -> dict[str, str]:
    env = dict(os.environ)
    env.pop("PYTHONPATH", None)
    env["PYTHONHASHSEED"] = "0"
    env["PYTHONDONTWRITEBYTECODE"] = "1"
    env["PYTHONUNBUFFERED"] = "1"
    return env


def run_probe(
    *,
    python_exe: Path,
    probe_path: Path,
    case: Case,
    pdf_path: Path,
    out_dir: Path,
    label: str,
    limit_as_mb: int,
) -> dict[str, Any]:
    json_out = out_dir / f"{case.id}.{label}.json"
    write_out = out_dir / f"{case.id}.{label}.out.pdf"
    for stale in (json_out, write_out):
        try:
            stale.unlink()
        except OSError:
            pass

    probe_timeout = max(5.0, float(case.timeout_s))
    parent_timeout = probe_timeout + 10.0
    command = [
        str(python_exe),
        str(probe_path),
        "--pdf",
        str(pdf_path),
        "--json-out",
        str(json_out),
        "--steps",
        ",".join(case.steps),
        "--resolve-path",
        json.dumps(list(case.resolve_path)),
        "--timeout",
        str(probe_timeout),
        "--limit-as-mb",
        str(limit_as_mb),
        "--label",
        label,
    ]
    if case.write:
        command += ["--write-out", str(write_out)]

    started = time.monotonic()
    timed_out = False
    returncode: int | None = None
    stdout = ""
    stderr = ""
    try:
        completed = subprocess.run(
            command,
            capture_output=True,
            text=True,
            timeout=parent_timeout,
            env=probe_env(),
            cwd=str(out_dir),
        )
        returncode = completed.returncode
        stdout = completed.stdout or ""
        stderr = completed.stderr or ""
    except subprocess.TimeoutExpired as exc:
        timed_out = True
        stdout = (exc.stdout or b"") if isinstance(exc.stdout, bytes) else (exc.stdout or "")
        stderr = (exc.stderr or b"") if isinstance(exc.stderr, bytes) else (exc.stderr or "")
        if isinstance(stdout, bytes):
            stdout = stdout.decode("utf-8", "replace")
        if isinstance(stderr, bytes):
            stderr = stderr.decode("utf-8", "replace")

    wall_s = round(time.monotonic() - started, 4)
    record = None
    if json_out.exists():
        try:
            record = json.loads(json_out.read_text(encoding="utf-8"))
        except Exception as exc:  # noqa: BLE001 - corrupted record is data
            record = None
            stderr += f"\n[probe] unreadable JSON record: {type(exc).__name__}: {exc}"

    if timed_out:
        status = "timeout"
    elif record is None:
        status = "crash"
    elif record.get("timeout"):
        status = "timeout"
    elif looks_like_environment_error(record):
        status = "environment"
    else:
        status = "ok"

    partial_output = None
    if case.write:
        exists = write_out.exists()
        partial_output = {
            "path": str(write_out),
            "exists": exists,
            "bytes": write_out.stat().st_size if exists else 0,
            "step_ok": bool(
                record
                and record.get("steps", {}).get("write", {}).get("status") == "ok"
            ),
        }

    return {
        "case_id": case.id,
        "status": status,
        "record": record,
        "process": {
            "returncode": returncode,
            "wall_s": wall_s,
            "timed_out": timed_out,
            "panic_suspected": looks_like_panic(stderr),
            "environment_error": status == "environment",
            "stdout_tail": stdout[-2000:],
            "stderr_tail": stderr[-6000:],
        },
        "partial_output": partial_output,
    }


def run_backend(
    *,
    backend: str,
    cases: list[Case],
    corpus_dir: Path,
    probe_path: Path,
    out_root: Path,
    limit_as_mb: int,
    manifest_entries: list[dict[str, Any]],
) -> dict[str, Any]:
    python_exe = PYTHON_EXE[backend]
    if not python_exe.exists():
        return {
            "backend": backend,
            "available": False,
            "python_exe": str(python_exe),
            "error": f"missing interpreter {python_exe}",
            "cases": {},
            "summary": {},
        }
    out_dir = out_root / backend
    out_dir.mkdir(parents=True, exist_ok=True)
    results: dict[str, Any] = {}
    generated = {entry["id"]: entry for entry in manifest_entries if entry.get("generated")}
    for case in cases:
        if case.id not in generated:
            continue
        run = run_probe(
            python_exe=python_exe,
            probe_path=probe_path,
            case=case,
            pdf_path=corpus_dir / f"{case.id}.pdf",
            out_dir=out_dir,
            label=backend,
            limit_as_mb=limit_as_mb,
        )
        record = run["record"] or {}
        results[case.id] = {
            "intent": case.intent,
            "category": case.category,
            "expectation": case.expectation,
            "steps_requested": list(case.steps),
            "resolve_path": list(case.resolve_path),
            "size_bytes": generated[case.id].get("size_bytes"),
            "sha256": generated[case.id].get("sha256"),
            "run": run,
            "timing": record.get("timing", {}),
            "import": record.get("import"),
            "rlimit": record.get("rlimit"),
            "limit_reached": record.get("limit_reached", False),
            "limit_reached_where": record.get("limit_reached_where", []),
            "limit_warnings": record.get("limit_warnings", []),
        }
    summary = summarize_backend(results)
    first_record = next(
        (item["run"]["record"] for item in results.values() if item["run"]["record"]),
        None,
    )
    return {
        "backend": backend,
        "available": True,
        "python_exe": str(python_exe),
        "python_version": None if not first_record else first_record.get("python"),
        "pypdf": None if not first_record else first_record.get("import"),
        "limit_as_mb": limit_as_mb,
        "cases": results,
        "summary": summary,
    }


def summarize_backend(results: dict[str, Any]) -> dict[str, Any]:
    summary = {
        "cases": len(results),
        "ok": 0,
        "errors": 0,
        "limit_reached": 0,
        "timeouts": 0,
        "crashes": 0,
        "panics": 0,
        "environment_errors": 0,
        "max_rss_bytes": 0,
        "total_cpu_s": 0.0,
        "total_wall_s": 0.0,
        "unavailable": 0,
    }
    for item in results.values():
        run = item["run"]
        record = run["record"] or {}
        if run["status"] == "timeout":
            summary["timeouts"] += 1
        if run["status"] == "crash":
            summary["crashes"] += 1
        if run["status"] == "environment":
            summary["environment_errors"] += 1
        if run["process"]["panic_suspected"]:
            summary["panics"] += 1
        if not (record.get("import") or {}).get("ok", False):
            summary["unavailable"] += 1
        if record.get("ok"):
            summary["ok"] += 1
        elif record.get("steps"):
            summary["errors"] += 1
        if item.get("limit_reached"):
            summary["limit_reached"] += 1
        timing = record.get("timing") or {}
        summary["max_rss_bytes"] = max(
            summary["max_rss_bytes"], int(timing.get("max_rss_bytes") or 0)
        )
        summary["total_cpu_s"] += float(timing.get("cpu_s") or 0.0)
        summary["total_wall_s"] += float(run["process"].get("wall_s") or 0.0)
    summary["total_cpu_s"] = round(summary["total_cpu_s"], 3)
    summary["total_wall_s"] = round(summary["total_wall_s"], 3)
    return summary



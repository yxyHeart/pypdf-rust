//! Auto-registration of ported modules.
//!
//! Every file dropped into `src/modules/*.rs` is compiled as a module and its
//! `register(&Bound<PyModule>) -> PyResult<()>` function is invoked when the
//! extension initialises.  This keeps module registration out of a shared file
//! so several porting tasks can add modules in parallel without edit conflicts.

use std::env;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("manifest dir"));
    let modules_dir = manifest_dir.join("src").join("modules");
    println!("cargo:rerun-if-changed=src/modules");
    println!("cargo:rerun-if-changed=build.rs");

    let mut entries: Vec<(String, PathBuf)> = Vec::new();
    if modules_dir.is_dir() {
        let read = fs::read_dir(&modules_dir).expect("read src/modules");
        for entry in read {
            let entry = entry.expect("dir entry");
            let path = entry.path();
            if path.extension().and_then(|ext| ext.to_str()) != Some("rs") {
                continue;
            }
            let stem = path
                .file_stem()
                .and_then(|stem| stem.to_str())
                .expect("file stem")
                .to_string();
            if stem.starts_with('_') {
                continue;
            }
            entries.push((stem, path));
        }
    }
    entries.sort_by(|left, right| left.0.cmp(&right.0));

    let mut generated = String::new();
    generated.push_str("// @generated by build.rs -- do not edit\n");
    for (stem, path) in &entries {
        generated.push_str(&format!(
            "#[path = {:?}]\npub mod {stem};\n",
            path.display().to_string()
        ));
    }
    generated.push_str(
        "\npub fn register_all(\n    module: &pyo3::Bound<'_, pyo3::types::PyModule>,\n) -> pyo3::PyResult<()> {\n",
    );
    for (stem, _) in &entries {
        generated.push_str(&format!("    {stem}::register(module)?;\n"));
    }
    generated.push_str("    Ok(())\n}\n");

    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));
    fs::write(out_dir.join("modules_generated.rs"), generated).expect("write generated modules");

    // Keep the checked-in source tree free of generated files.
    let _ = Path::new(&modules_dir);
}
